/** 构建素材库（自动按 id 去重，移除错误重复项） */
function buildLibrary(): StickerDef[] {
  const seen = new Set<string>()
  const out: StickerDef[] = []
  for (const [category, items] of RAW) {
    for (const [id, char, name] of items) {
      if (seen.has(id)) {
        if (process.env.NODE_ENV !== 'production') {
          console.warn('[StickerLibrary] 重复素材已移除:', id, name)
        }
        continue
      }
      seen.add(id)
      out.push({ id, char, name, category })
    }
  }
  return out
}

/** 全量素材（已去重） */
export const STICKER_LIBRARY: StickerDef[] = buildLibrary()

/** 按分类取素材 */
export function getStickersByCategory(cat: StickerCategory): StickerDef[] {
  return STICKER_LIBRARY.filter(s => s.category === cat)
}
